"""Sample figures from the lossless sample grids written by scripts/sample_grid.py of the code (data/samples/): a
same-noise comparison of the three 1e21 models, the compute-optimal models of both routes at every budget, and the
full grid of the converted XL model.

  python analysis/sample_figs.py  ->  paper/figures/fig_samples_*.jpg, paper/tables/fig_samples_*.tex
"""
import json

import numpy as np
from PIL import Image

from common import DATA, FIGS as OUT, TAB

S = f"{DATA}/samples/samples"
T = 256


def save_jpeg(img, name, quality=93):
    Image.fromarray(img).convert("RGB").save(f"{OUT}/{name}.jpg", quality=quality, subsampling=0)


def tiles(run, meta):
    g = np.array(Image.open(f"{S}/{run}.png"))
    n = meta["n"]
    return {(c, j): g[i * T:(i + 1) * T, j * T:(j + 1) * T] for i, c in enumerate(meta["classes"]) for j in range(n)}


def grid(rows, size=160, gap=2):
    h = len(rows) * size + (len(rows) - 1) * gap
    w = len(rows[0]) * size + (len(rows[0]) - 1) * gap
    out = np.full((h, w, 3), 252, dtype=np.uint8)
    for i, row in enumerate(rows):
        for j, t in enumerate(row):
            im = np.array(Image.fromarray(t).resize((size, size), Image.LANCZOS))
            out[i * (size + gap):i * (size + gap) + size, j * (size + gap):j * (size + gap) + size] = im
    return out


def main():
    """Same-noise comparison of the three 1e21 models (rows) and the full grid of the converted XL model."""
    meta = json.load(open(f"{S}/meta.json"))
    conv, nat, ms = "v2_XL_1e21_f0.60_s0", "v1_XL_1e21_cd_s0", "v2_H_1e21_cd_s0"
    tc, tn, tm = tiles(conv, meta), tiles(nat, meta), tiles(ms, meta)
    cls = [88, 207, 279, 360, 387, 417, 973, 933, 980, 291]
    rows = [[tc[(c, 2)] for c in cls], [tn[(c, 2)] for c in cls], [tm[(c, 2)] for c in cls]]
    save_jpeg(grid(rows, size=192, gap=3), "fig_samples_compare_grid")
    tex_labels("fig_samples_compare", "fig_samples_compare_grid.jpg",
               [f"pretrain$\\to$convert XL\\\\1 NFE, FID {meta['runs'][conv]['fid50k']:.2f}",
                f"native XL\\\\1 NFE, FID {meta['runs'][nat]['fid50k']:.2f}",
                f"multi-step H\\\\50 steps, FID {meta['runs'][ms]['fid50k']:.2f}"], wimg=0.85)
    # full grid of the converted model (16 classes x 8)
    rows = [[tc[(c, j)] for j in range(meta["n"])] for c in meta["classes"]]
    save_jpeg(grid(rows, size=160, gap=2), "fig_samples_full", quality=90)


def tex_labels(name, img, labels, wimg=0.85, heads=None):
    """paper/tables/<name>.tex: the image at wimg of the line width and its row labels in the text font, each centred on
    its row (rows of equal height); heads: optional column headers [(text, x0, x1)] in fractions of the image width."""
    k = len(labels)
    body = "\\vspace*{\\fill}\n" + "\n\\vspace{\\fill}\\vspace{\\fill}\n".join(f"{lab}\\par" for lab in labels) + "\n\\vspace*{\\fill}"
    L = [f"% generated by analysis/sample_figs.py ({k} rows)",
         f"\\sbox{{\\sampbox}}{{\\includegraphics[width={wimg}\\linewidth]{{{img}}}}}"]
    if heads:
        L.append(f"\\hfill\\begin{{minipage}}{{{wimg}\\linewidth}}\\scriptsize\\makebox[0pt][l]{{}}%")
        for t, x0, x1 in heads:
            L.append(f"\\makebox[0pt][l]{{\\hspace*{{{(x0 + x1) / 2:.4f}\\linewidth}}\\makebox[0pt][c]{{{t}}}}}%")
        L.append("\\end{minipage}\\\\[1pt]")
    L += [f"\\begin{{minipage}}[b][\\ht\\sampbox][s]{{{0.985 - wimg:.3f}\\linewidth}}\\raggedleft\\scriptsize",
          body, "\\end{minipage}\\hfill\\usebox{\\sampbox}"]
    open(f"{TAB}/{name}.tex", "w").write("\n".join(L) + "\n")


def budget():
    """Compute-optimal 1-NFE models of both routes at every budget, the same noise per column
    (data/samples/samples_budget): rows = budgets, left = pretrain->convert, right = native."""
    SB = S + "_budget"
    meta = json.load(open(f"{SB}/meta.json"))
    conv = ["r3_S_1e19_f0.50_s0", "r3_M_3e19_f0.65_s0", "r3_M_1e20_f0.65_s0", "r3_XL_3e20_f0.50_s0", "v2_XL_1e21_f0.60_s0"]
    nat = ["r2_S_1e19_cd_s0", "r2_S_3e19_cd_s0", "r2_M_1e20_cd_s0", "r2_M_3e20_cd_s0", "v1_XL_1e21_cd_s0"]
    extra = {"r2_S_3e19_cd_s0": SB + "_S3e19"}  # sampled later with the same seed, classes and n (same noise)
    for r, d in extra.items():
        meta["runs"][r] = json.load(open(f"{d}/meta.json"))["runs"][r]
    buds = ["$10^{19}$", "$3{\\times}10^{19}$", "$10^{20}$", "$3{\\times}10^{20}$", "$10^{21}$"]
    cls, j = [88, 207, 387, 933], 0

    def load(run):
        g = np.array(Image.open(f"{extra.get(run, SB)}/{run}.png"))
        return {c: g[i * T:(i + 1) * T, j * T:(j + 1) * T] for i, c in enumerate(meta["classes"])}
    size = 160
    blocks = []
    for runs in (conv, nat):
        rows = [[load(r)[c] for c in cls] for r in runs]
        blocks.append(grid(rows, size=size, gap=3))
    sep = np.full((blocks[0].shape[0], 40, 3), 252, dtype=np.uint8)
    img = np.concatenate([blocks[0], sep, blocks[1]], axis=1)
    wb = blocks[0].shape[1]
    save_jpeg(img, "fig_samples_budget_grid")
    W_ = img.shape[1]
    tex_labels("fig_samples_budget", "fig_samples_budget_grid.jpg",
               [f"$C={b.strip('$')}$\\\\convert {meta['runs'][rc]['size']}: {meta['runs'][rc]['fid50k']:.2f}\\\\"
                f"native {meta['runs'][rn]['size']}: {meta['runs'][rn]['fid50k']:.2f}" for b, rc, rn in zip(buds, conv, nat)],
               wimg=0.86, heads=[("pretrain$\\to$convert (1 NFE)", 0, wb / W_), ("native one-step (1 NFE)", (wb + 40) / W_, 1.0)])


if __name__ == "__main__":
    main()
    budget()
    print("sample figures written")
